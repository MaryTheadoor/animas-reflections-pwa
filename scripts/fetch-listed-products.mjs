#!/usr/bin/env node
/**
 * Snapshot the listed products from Firestore into a committed module, so the
 * sitemap can name every product page.
 *
 * The site is a static export and products live in Firestore, so nothing at
 * build time knew which products exist — which is why sitemap.xml carried 18
 * route entries and zero products, and every product page shipped the same
 * `<title>Product Details</title>` with the product name appearing nowhere.
 *
 * Same contract as scripts/fetch-seo-config.mjs: products are publicly readable,
 * the snapshot is written only when it changes, and if Firestore is unreachable
 * the committed snapshot is kept so a build never depends on the network and a
 * fresh clone still builds.
 *
 * Only `active` products are carried: an unlisted product must not appear in the
 * sitemap, or we would be advertising pages the shop hides.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const TARGET = join(ROOT, "src", "lib", "products.generated.ts");
const PROJECT = process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID || "animas-reflections-pwa";
const BASE =
  "https://firestore.googleapis.com/v1/projects/" +
  PROJECT +
  "/databases/(default)/documents/products";
const TIMEOUT_MS = 15000;

/** Firestore REST value -> plain JSON. */
function decodeValue(v) {
  if (!v || typeof v !== "object") return null;
  if ("stringValue" in v) return v.stringValue;
  if ("booleanValue" in v) return v.booleanValue;
  if ("integerValue" in v) return Number(v.integerValue);
  if ("doubleValue" in v) return Number(v.doubleValue);
  if ("nullValue" in v) return null;
  if ("mapValue" in v) return decodeFields(v.mapValue.fields);
  if ("arrayValue" in v) return (v.arrayValue.values || []).map(decodeValue);
  return null;
}

function decodeFields(fields) {
  const out = {};
  for (const key of Object.keys(fields || {})) out[key] = decodeValue(fields[key]);
  return out;
}

async function fetchAll() {
  const docs = [];
  let token = null;
  for (let page = 0; page < 20; page++) {
    const url = BASE + "?pageSize=300" + (token ? "&pageToken=" + token : "");
    const res = await fetch(url, { signal: AbortSignal.timeout(TIMEOUT_MS) });
    if (!res.ok) throw new Error("HTTP " + res.status);
    const body = await res.json();
    docs.push(...(body.documents || []));
    token = body.nextPageToken;
    if (!token) break;
  }
  return docs;
}

function snapshotOf(docs) {
  return docs
    .map((doc) => ({
      id: doc.name.split("/").pop(),
      ...decodeFields(doc.fields),
    }))
    .filter((p) => p.active === true && typeof p.name === "string" && p.name.trim())
    .map((p) => ({ id: p.id, name: p.name }))
    .sort((a, b) => a.id.localeCompare(b.id));
}

function render(products) {
  return [
    "/* AUTO-GENERATED by scripts/fetch-listed-products.mjs - DO NOT EDIT BY HAND.",
    "   Snapshot of the LISTED products in Firestore, used to enumerate product",
    "   pages in sitemap.xml. Regenerated on every build; when Firestore is",
    "   unreachable the committed snapshot (last known good) is kept. */",
    "",
    "export interface ListedProduct {",
    "  id: string;",
    "  name: string;",
    "}",
    "",
    "export const LISTED_PRODUCTS: ListedProduct[] = " +
      JSON.stringify(products, null, 2) +
      ";",
    "",
  ].join("\n");
}

function write(products) {
  const next = render(products);
  const prev = existsSync(TARGET) ? readFileSync(TARGET, "utf8") : "";
  // Write only on change so the file does not churn a diff on every build.
  if (prev === next) {
    console.log("[listed-products] unchanged (" + products.length + ")");
    return;
  }
  writeFileSync(TARGET, next);
  console.log("[listed-products] wrote " + products.length + " listed products");
}

try {
  const products = snapshotOf(await fetchAll());
  if (products.length === 0) {
    // An empty read is far more likely to be a transient fault than a shop with
    // nothing for sale; keep the last known good list rather than emptying the
    // sitemap.
    console.warn("[listed-products] Firestore returned no listed products — keeping the committed snapshot");
  } else {
    write(products);
  }
} catch (err) {
  console.warn(
    "[listed-products] could not reach Firestore (" +
      (err?.message ?? err) +
      ") — keeping the committed snapshot",
  );
}
