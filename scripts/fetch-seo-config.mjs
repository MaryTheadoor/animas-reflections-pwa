#!/usr/bin/env node
/**
 * Snapshot the CMS-managed SEO config from Firestore into a committed module.
 *
 * Runs on `prebuild`. The site is a static export, so SEO copy has to be baked
 * into the HTML at build time; this is what makes it editable from Admin -> SEO
 * without anyone touching source.
 *
 * config/seo is publicly readable (public marketing copy). If Firestore is
 * unreachable the committed snapshot is kept, so a build never depends on the
 * network and a fresh clone still builds. Output is validated at load by
 * normalizeSeoConfig() in src/lib/seo-config.ts.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const TARGET = join(ROOT, "src", "lib", "seo-content.generated.ts");
const PROJECT = process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID || "animas-reflections-pwa";
const ENDPOINT =
  "https://firestore.googleapis.com/v1/projects/" +
  PROJECT +
  "/databases/(default)/documents/config/seo";

/** Firestore REST value -> plain JSON. */
function decodeValue(v) {
  if (!v || typeof v !== "object") return null;
  if ("stringValue" in v) return v.stringValue;
  if ("booleanValue" in v) return v.booleanValue;
  if ("integerValue" in v) return Number(v.integerValue);
  if ("doubleValue" in v) return Number(v.doubleValue);
  if ("timestampValue" in v) return v.timestampValue;
  if ("nullValue" in v) return null;
  if ("mapValue" in v) return decodeFields(v.mapValue.fields);
  if ("arrayValue" in v) return (v.arrayValue.values || []).map(decodeValue);
  return null;
}

function decodeFields(fields) {
  const out = {};
  for (const key of Object.keys(fields || {})) out[key] = decodeValue(fields[key]);
  return out;
}

/**
 * The build only needs the copy. updatedAt/updatedBy are admin-display metadata
 * that the admin UI reads live from Firestore — carrying them here made the
 * committed snapshot differ on every save, so `npm run build` dirtied the
 * working tree and "is the repo clean?" stopped being a usable check.
 */
/** Fixed key order, so the snapshot does not churn when Firestore returns a
 *  document's fields in a different order (it is not guaranteed stable). */
const KEYWORD_KEYS = [
  "slug", "keyword", "headline", "title", "description",
  "body", "ctaLabel", "ctaHref", "published", "order",
];

function canonicalKeyword(k) {
  const out = {};
  for (const key of KEYWORD_KEYS) if (k[key] !== undefined) out[key] = k[key];
  // Anything unrecognised is kept rather than silently dropped.
  for (const key of Object.keys(k)) if (!(key in out)) out[key] = k[key];
  return out;
}

function snapshotOf(config) {
  const rawPages = config.pages ?? {};
  const pages = {};
  for (const path of Object.keys(rawPages).sort()) {
    const p = rawPages[path] ?? {};
    pages[path] = { title: p.title, description: p.description };
  }
  return { pages, keywords: (config.keywords ?? []).map(canonicalKeyword) };
}

function render(config) {
  return [
    "/* AUTO-GENERATED by scripts/fetch-seo-config.mjs - DO NOT EDIT BY HAND.",
    "   Snapshot of the Firestore doc config/seo, edited in Admin -> SEO.",
    "   Regenerated on every build; when Firestore is unreachable the committed",
    "   snapshot (last known good) is kept. */",
    "",
    "export const SEO_CONTENT: unknown = " + JSON.stringify(snapshotOf(config), null, 2) + ";",
    "",
  ].join("\n");
}

function write(config) {
  const next = render(config);
  const prev = existsSync(TARGET) ? readFileSync(TARGET, "utf8") : "";
  // Write only on change so the file does not churn a diff on every build.
  if (prev === next) {
    console.log("[seo-config] unchanged");
    return;
  }
  writeFileSync(TARGET, next);
  const keywords = Array.isArray(config.keywords) ? config.keywords.length : 0;
  const pages = config.pages ? Object.keys(config.pages).length : 0;
  console.log(
    "[seo-config] updated - " + pages + " page override(s), " + keywords + " keyword(s)"
  );
}

async function main() {
  let config = { pages: {}, keywords: [] };
  try {
    // A hung socket must not stall prebuild forever; 15s is generous for a
    // single Firestore document read, and the fallback below keeps the snapshot.
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), 15000);
    let res;
    try {
      res = await fetch(ENDPOINT, {
        headers: { accept: "application/json" },
        signal: controller.signal,
      });
    } finally {
      clearTimeout(timer);
    }
    if (res.status === 404) {
      // A 404 is legitimate on a fresh project, but if the committed snapshot
      // has real content then the document was DELETED - and silently writing an
      // empty config would drop every page override and keyword page from the
      // next build. Keep the snapshot and say so loudly instead.
      const emptyRendered = render({ pages: {}, keywords: [] });
      const hasContent = existsSync(TARGET) && readFileSync(TARGET, "utf8") !== emptyRendered;
      if (hasContent) {
        console.warn(
          "[seo-config] config/seo is MISSING (HTTP 404) but the committed snapshot has content. " +
            "Keeping the snapshot so the build does not silently drop your keyword pages. " +
            "If the document was deleted by accident, re-save it from Admin -> SEO."
        );
        return;
      }
      console.log("[seo-config] config/seo does not exist yet - using an empty config");
    } else if (!res.ok) {
      throw new Error("HTTP " + res.status);
    } else {
      config = decodeFields((await res.json()).fields);
      // A 200 carrying an EMPTY document is as destructive as a 404: writing it
      // would drop every page override and keyword page from the next build. Only
      // guard when the committed snapshot actually has content, so a genuinely
      // fresh project still gets its empty config written.
      const empty =
        Object.keys(config.pages ?? {}).length === 0 && (config.keywords ?? []).length === 0;
      if (empty) {
        const emptyRendered = render({ pages: {}, keywords: [] });
        const hasContent = existsSync(TARGET) && readFileSync(TARGET, "utf8") !== emptyRendered;
        if (hasContent) {
          console.warn(
            "[seo-config] config/seo came back EMPTY (HTTP 200) but the committed snapshot has content. " +
              "Keeping the snapshot so the build does not silently drop your keyword pages. " +
              "If you meant to clear it, do that deliberately rather than through a failed read."
          );
          return;
        }
      }
    }
  } catch (err) {
    const reason = err && err.message ? err.message : String(err);
    if (existsSync(TARGET)) {
      // Falling back is the right call for a transient network blip, and the
      // wrong call to make quietly: this snapshot is what gets baked into the
      // published HTML, so if it is stale the site ships SEO copy of unknown
      // age with nothing red anywhere. Announce it in a form a CI run surfaces
      // at the top of the page, and let --strict turn it into a failure for
      // anyone who would rather block the publish.
      const msg =
        "[seo-config] fetch failed (" +
        reason +
        ") - keeping the committed snapshot. The published SEO copy may be out of date.";
      if (process.env.GITHUB_ACTIONS === "true") {
        console.log("::warning title=SEO snapshot is stale::" + msg);
      }
      console.warn(msg);
      if (process.argv.includes("--strict")) {
        console.error("[seo-config] --strict: refusing to build against a snapshot of unknown age.");
        process.exit(1);
      }
      return;
    }
    // No committed snapshot to fall back on means the generated file was
    // deleted. Failing loudly beats building a site with no page overrides and
    // no keyword pages, which would deploy as a silent SEO regression.
    console.error(
      "[seo-config] fetch failed (" +
        reason +
        ") and there is no committed snapshot at " +
        TARGET +
        " to fall back on. Failing the build rather than publishing a site with no keyword pages."
    );
    process.exit(1);
  }
  write(config);
}

main();
